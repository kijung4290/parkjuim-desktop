const { contextBridge, ipcRenderer } = require('electron');
const on = (channel, callback) => { const listener = (_event, data) => callback(data); ipcRenderer.on(channel, listener); return () => ipcRenderer.removeListener(channel, listener); };
contextBridge.exposeInMainWorld('park', Object.freeze({
  settings: () => ipcRenderer.invoke('settings:get'),
  setPortrait: data => ipcRenderer.send('pet:portrait',data),
  onPortrait: callback => on('pet:portrait',callback),
  modelError: () => ipcRenderer.send('pet:model-error'),
  customModels: () => ipcRenderer.invoke('models:list'),
  importModel: () => ipcRenderer.invoke('models:add'),
  importModelData: input => ipcRenderer.invoke('models:import',input),
  deleteModel: id => ipcRenderer.invoke('models:delete',id),
  saveSettings: input => ipcRenderer.invoke('settings:save', input),
  aiModels: input => ipcRenderer.invoke('ai:models', input),
  send: (id, input) => ipcRenderer.invoke('chat:send', id, input),
  resetChat: () => ipcRenderer.invoke('chat:reset'),
  historyList: () => ipcRenderer.invoke('history:list'),
  historyOpen: id => ipcRenderer.invoke('history:open', id),
  historyRename: (id,title) => ipcRenderer.invoke('history:rename', id,title),
  historyDelete: id => ipcRenderer.invoke('history:delete', id),
  chooseAttachments: remaining => ipcRenderer.invoke('attachments:choose', remaining),
  removeAttachment: id => ipcRenderer.invoke('attachments:remove', id),
  openSource: id => ipcRenderer.invoke('chat:source', id),
  cancel: () => ipcRenderer.invoke('chat:cancel'),
  toggleChat: () => ipcRenderer.invoke('pet:chat'),
  closeChat: () => ipcRenderer.invoke('chat:hide'),
  menu: () => ipcRenderer.invoke('pet:menu'),
  pointerMoved: () => ipcRenderer.send('pet:pointer'),
  drag: phase => ipcRenderer.send('pet:drag', phase),
  voiceStart: () => ipcRenderer.invoke('voice:start'),
  voiceStop: () => ipcRenderer.invoke('voice:stop'),
  dictate: () => ipcRenderer.invoke('voice:dictate'),
  speak: text => ipcRenderer.invoke('voice:speak', text),
  voices: input => ipcRenderer.invoke('voice:voices', input),
  previewVoice: input => ipcRenderer.invoke('voice:preview', input),
  playback: (id, state) => ipcRenderer.send('voice:playback', id, state),
  stopSpeaking: () => ipcRenderer.invoke('voice:silence'),
  openLink: name => ipcRenderer.invoke('link:open', name),
  updateState: () => ipcRenderer.invoke('update:get'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: callback => on('update:state', callback),
  onPetState: callback => on('pet:state', callback),
  onSettings: callback => on('settings:changed', callback),
  onChat: callback => on('chat:event', callback),
  onVoice: callback => on('voice:event', callback),
  onView: callback => on('view:open', callback)
}));
